-- Class growing, step one: the class apple tree. Students water it (paid from their balance),
-- completed tasks and the teacher's sunshine add drops, and when the drops reach the goal the
-- teacher harvests it: every active student receives the reward and a new tree starts.
-- Apply as the migration/BYPASSRLS owner in one transaction; the runtime grants are in
-- provisioning/runtimeGrants.sql.
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_roles WHERE rolname=current_user AND (rolsuper OR rolbypassrls)) THEN
    RAISE EXCEPTION 'class tree requires migration/BYPASSRLS ownership';
  END IF;
END $$;

-- Watering is a purchase (GROWTH_SPEND); a harvest reward is income (GROWTH_REWARD).
ALTER TABLE public.transactions DROP CONSTRAINT transactions_kind_check;
ALTER TABLE public.transactions ADD CONSTRAINT transactions_kind_check CHECK (kind IN (
  'CHECKOUT', 'CANCELLATION', 'ADMIN_ADJUSTMENT', 'TASK_REWARD', 'LEGACY', 'GROWTH_SPEND', 'GROWTH_REWARD'));

ALTER TABLE public.operations DROP CONSTRAINT operations_kind_check;
ALTER TABLE public.operations ADD CONSTRAINT operations_kind_check CHECK (operation_kind IN (
  'CHECKOUT', 'CANCELLATION', 'ADMIN_ADJUSTMENT', 'TASK_REWARD', 'STUDENT_ADMIN', 'PRODUCT_ADMIN',
  'PROMOTION_ADMIN', 'TASK_ADMIN', 'SETTINGS_ADMIN', 'MIGRATION_IMPORT', 'CUTOVER', 'EXPORT', 'GROWTH'));

-- One row per class once the teacher opens the tree settings.
CREATE TABLE public.growth_settings (
  tenant_id uuid PRIMARY KEY REFERENCES public.tenants(id) ON DELETE CASCADE,
  tree_enabled boolean NOT NULL DEFAULT false,
  water_price bigint NOT NULL DEFAULT 10,
  water_daily_limit integer NOT NULL DEFAULT 2,
  task_drops integer NOT NULL DEFAULT 1,
  target_weeks integer NOT NULL DEFAULT 4,
  goal_override bigint,
  reward_amount bigint NOT NULL DEFAULT 100,
  reward_coupon text NOT NULL DEFAULT '',
  version bigint NOT NULL DEFAULT 1,
  updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT growth_settings_water_check CHECK (water_price BETWEEN 0 AND 1000000 AND water_daily_limit BETWEEN 0 AND 10),
  CONSTRAINT growth_settings_task_drops_check CHECK (task_drops BETWEEN 0 AND 10),
  CONSTRAINT growth_settings_weeks_check CHECK (target_weeks BETWEEN 1 AND 20),
  CONSTRAINT growth_settings_goal_check CHECK (goal_override IS NULL OR goal_override BETWEEN 1 AND 1000000),
  CONSTRAINT growth_settings_reward_check CHECK (reward_amount BETWEEN 0 AND 1000000),
  CONSTRAINT growth_settings_coupon_check CHECK (reward_coupon = btrim(reward_coupon) AND char_length(reward_coupon) <= 30),
  CONSTRAINT growth_settings_version_check CHECK (version >= 1)
);

-- Tree No. 1, 2, ... of a class. At most one grows at a time; a harvested tree keeps what it gave.
CREATE TABLE public.class_trees (
  tenant_id uuid NOT NULL REFERENCES public.tenants(id) ON DELETE CASCADE,
  tree_no integer NOT NULL,
  goal bigint NOT NULL,
  drops bigint NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT 'GROWING',
  started_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  harvested_at timestamptz,
  harvest_operation_id text,
  harvest_recipients integer,
  harvest_reward_amount bigint,
  harvest_coupon text,
  version bigint NOT NULL DEFAULT 1,
  CONSTRAINT class_trees_pkey PRIMARY KEY (tenant_id, tree_no),
  CONSTRAINT class_trees_no_check CHECK (tree_no >= 1),
  CONSTRAINT class_trees_goal_check CHECK (goal BETWEEN 1 AND 1000000),
  CONSTRAINT class_trees_drops_check CHECK (drops BETWEEN 0 AND 9007199254740991),
  CONSTRAINT class_trees_status_check CHECK (status IN ('GROWING', 'HARVESTED')),
  CONSTRAINT class_trees_harvest_shape_check CHECK (
    (status = 'GROWING' AND harvested_at IS NULL AND harvest_operation_id IS NULL AND harvest_recipients IS NULL
      AND harvest_reward_amount IS NULL AND harvest_coupon IS NULL)
    OR (status = 'HARVESTED' AND harvested_at >= started_at AND harvest_operation_id IS NOT NULL
      AND harvest_recipients >= 0 AND harvest_reward_amount >= 0 AND harvest_coupon IS NOT NULL)),
  CONSTRAINT class_trees_version_check CHECK (version >= 1)
);
CREATE UNIQUE INDEX class_trees_one_growing ON public.class_trees (tenant_id) WHERE status = 'GROWING';

-- Every change to a tree's drops, append-only. A cancelled watering or task reward adds a CANCEL row.
CREATE TABLE public.tree_drops (
  tenant_id uuid NOT NULL,
  drop_id text NOT NULL,
  tree_no integer NOT NULL,
  event_sequence bigint GENERATED BY DEFAULT AS IDENTITY,
  source text NOT NULL,
  student_id text,
  amount integer NOT NULL,
  transaction_id text,
  operation_id text,
  note text,
  created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT tree_drops_pkey PRIMARY KEY (tenant_id, drop_id),
  CONSTRAINT tree_drops_sequence_unique UNIQUE (tenant_id, event_sequence),
  CONSTRAINT tree_drops_tree_fk FOREIGN KEY (tenant_id, tree_no) REFERENCES public.class_trees (tenant_id, tree_no),
  CONSTRAINT tree_drops_student_fk FOREIGN KEY (tenant_id, student_id) REFERENCES public.students (tenant_id, student_id),
  CONSTRAINT tree_drops_transaction_fk FOREIGN KEY (tenant_id, transaction_id) REFERENCES public.transactions (tenant_id, transaction_id),
  CONSTRAINT tree_drops_id_check CHECK (drop_id = btrim(drop_id) AND length(drop_id) BETWEEN 1 AND 200),
  CONSTRAINT tree_drops_source_check CHECK (source IN ('WATER', 'TASK', 'SUN', 'CANCEL')),
  CONSTRAINT tree_drops_amount_check CHECK (amount <> 0 AND amount BETWEEN -1000000 AND 1000000
    AND (source = 'CANCEL') = (amount < 0)),
  CONSTRAINT tree_drops_student_shape_check CHECK ((source = 'SUN') = (student_id IS NULL)),
  CONSTRAINT tree_drops_note_check CHECK (note IS NULL OR (note = btrim(note) AND char_length(note) BETWEEN 1 AND 40))
);
CREATE INDEX tree_drops_tree_idx ON public.tree_drops (tenant_id, tree_no, event_sequence);
CREATE INDEX tree_drops_student_day_idx ON public.tree_drops (tenant_id, student_id, created_at) WHERE source = 'WATER';
CREATE INDEX tree_drops_transaction_idx ON public.tree_drops (tenant_id, transaction_id) WHERE transaction_id IS NOT NULL;
CREATE TRIGGER tree_drops_immutable BEFORE UPDATE OR DELETE ON public.tree_drops
  FOR EACH ROW EXECUTE FUNCTION reject_immutable_row();

-- Coupons a teacher gives as a reward ("자리 바꾸기권"). The teacher marks one used when it is spent.
CREATE TABLE public.reward_vouchers (
  tenant_id uuid NOT NULL,
  voucher_id text NOT NULL,
  student_id text NOT NULL,
  source text NOT NULL,
  source_ref text NOT NULL,
  title text NOT NULL,
  operation_id text NOT NULL,
  issued_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  used_at timestamptz,
  CONSTRAINT reward_vouchers_pkey PRIMARY KEY (tenant_id, voucher_id),
  CONSTRAINT reward_vouchers_student_fk FOREIGN KEY (tenant_id, student_id) REFERENCES public.students (tenant_id, student_id),
  CONSTRAINT reward_vouchers_id_check CHECK (voucher_id = btrim(voucher_id) AND length(voucher_id) BETWEEN 1 AND 200),
  CONSTRAINT reward_vouchers_source_check CHECK (source IN ('TREE_HARVEST')),
  CONSTRAINT reward_vouchers_title_check CHECK (title = btrim(title) AND char_length(title) BETWEEN 1 AND 30),
  CONSTRAINT reward_vouchers_used_check CHECK (used_at IS NULL OR used_at >= issued_at)
);
CREATE INDEX reward_vouchers_student_idx ON public.reward_vouchers (tenant_id, student_id, issued_at DESC);

DO $rls$
DECLARE table_name text;
BEGIN
  FOREACH table_name IN ARRAY ARRAY['growth_settings', 'class_trees', 'tree_drops', 'reward_vouchers']
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
    EXECUTE format('ALTER TABLE public.%I FORCE ROW LEVEL SECURITY', table_name);
    EXECUTE format(
      'CREATE POLICY %I ON public.%I USING (tenant_id = NULLIF(current_setting(''app.tenant_id'', true), '''')::uuid) WITH CHECK (tenant_id = NULLIF(current_setting(''app.tenant_id'', true), '''')::uuid)',
      table_name || '_tenant_isolation', table_name
    );
    EXECUTE format('REVOKE ALL ON public.%I FROM PUBLIC', table_name);
  END LOOP;
END
$rls$;
